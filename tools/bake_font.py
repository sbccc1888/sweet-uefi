#!/usr/bin/env python3
"""bake_font.py -- rasterise a TTF into antialiased alpha atlases for the UEFI UI.

Why bake instead of shipping a bitmap console font: the UI is the point of this
application, and an 8x16 VGA font at 3x scale looks like 1993. Antialiased
coverage from a real typeface costs one small C array per size and renders as
smooth text on the panel.

Output is one C file with, per size:
  * a byte alpha atlas (0..255 coverage), one byte per pixel,
  * a per-glyph rect and advance,
  * the first/last codepoint it covers.

Usage:
  tools/bake_font.py --ttf /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf \
      --out src/font.c --sizes 44,28,20
"""
import argparse
import os

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    raise SystemExit("Pillow is required: apt install python3-pil")

FIRST = 32
LAST = 126

# Sizes the UI asks for, by name, so the C side does not hard-code indices.
SIZE_NAMES = ["title", "body", "small"]


def bake(ttf, size):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent

    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        img = Image.new("L", (size * 3, height + size), 0)
        d = ImageDraw.Draw(img)
        d.text((size, size // 2), ch, fill=255, font=font)
        adv = int(round(font.getlength(ch)))
        bbox = img.getbbox()
        if bbox is None:
            # No ink (space and friends). The ADVANCE still matters -- that is
            # the whole width of a space -- so record it and leave the ink empty.
            glyphs.append((code, 0, 0, 0, 0, adv))
            continue
        crop = img.crop(bbox)
        glyphs.append((code, bbox[0] - size, bbox[1] - size // 2,
                       crop.width, crop.height, adv, crop))

    # pack glyph bitmaps into one atlas, left to right, wrapping at 512px
    atlas_w = 512
    x = y = 0
    row_h = 0
    placed = []
    for g in glyphs:
        if len(g) == 6:
            placed.append((g, 0, 0, 0, 0))
            continue
        code, ox, oy, w, h, adv, crop = g
        if x + w > atlas_w:
            x = 0
            y += row_h
            row_h = 0
        placed.append(((code, ox, oy, w, h, adv), x, y, crop))
        x += w + 1
        row_h = max(row_h, h + 1)
    atlas_h = y + row_h

    data = bytearray(atlas_w * atlas_h)
    rects = []
    for item in placed:
        if len(item) == 5:
            # ink-less glyph: keep its advance, which is its entire width
            g = item[0]
            rects.append((g[0], 0, 0, 0, 0, g[5], 0, 0))
            continue
        (code, ox, oy, w, h, adv), ax, ay, crop = item
        px = crop.load()
        for j in range(h):
            base = (ay + j) * atlas_w + ax
            for i in range(w):
                data[base + i] = px[i, j]
        rects.append((code, ox, oy, w, h, adv, ax, ay))

    return dict(size=size, ascent=ascent, descent=descent, height=height,
                atlas_w=atlas_w, atlas_h=atlas_h, data=bytes(data),
                rects=rects)


def emit(bakes, out_path, ttf_name):
    lines = []
    w = lines.append
    w("/* Generated by tools/bake_font.py -- do not edit by hand.")
    w(" *")
    w(" * Typeface: %s" % os.path.basename(ttf_name))
    w(" * Coverage: printable ASCII %d..%d, antialiased 8-bit alpha."
      % (FIRST, LAST))
    w(" *")
    w(" * Each size is an alpha atlas plus a per-glyph rect. Alpha rather than a")
    w(" * 1-bit mask so the panel shows smooth edges instead of stair-steps.")
    w(" */")
    w("")
    w('#include "font.h"')
    w("")

    for b in bakes:
        n = b["size"]
        w("static const unsigned char atlas_%d[] = {" % n)
        d = b["data"]
        for i in range(0, len(d), 24):
            w("    " + ",".join("%d" % v for v in d[i:i + 24]) + ",")
        w("};")
        w("")
        w("static const struct baked_glyph glyphs_%d[] = {" % n)
        for (code, ox, oy, gw, gh, adv, ax, ay) in b["rects"]:
            w("    { %d, %d, %d, %d, %d, %d, %d, %d }," %
              (code, ox, oy, gw, gh, adv, ax, ay))
        w("};")
        w("")

    w("const struct baked_font g_fonts[FONT_COUNT] = {")
    for b, name in zip(bakes, SIZE_NAMES):
        n = b["size"]
        w("    [FONT_%s] = { %d, %d, %d, %d, %d, %d, atlas_%d, glyphs_%d,"
          % (name.upper(), n, b["ascent"], b["descent"], b["height"],
             b["atlas_w"], b["atlas_h"], n, n))
        w("                  (int)(sizeof(glyphs_%d) / sizeof(glyphs_%d[0])) },"
          % (n, n))
    w("};")
    w("")

    with open(out_path, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d bytes)" % (out_path, os.path.getsize(out_path)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--sizes", default="44,28,20")
    a = ap.parse_args()

    sizes = [int(s) for s in a.sizes.split(",")]
    if len(sizes) != len(SIZE_NAMES):
        raise SystemExit("need exactly %d sizes (%s), got %d"
                         % (len(SIZE_NAMES), ",".join(SIZE_NAMES), len(sizes)))
    bakes = [bake(a.ttf, s) for s in sizes]
    emit(bakes, a.out, a.ttf)


if __name__ == "__main__":
    main()
